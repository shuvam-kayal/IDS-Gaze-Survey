param(
    [string]$TestDatabaseName = "attention_test"
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$Root = (Resolve-Path (Join-Path $PSScriptRoot ".." )).Path
Set-Location $Root
$ComposeFile = Join-Path $Root "docker-compose.yml"
$EnvExample = Join-Path $Root ".env.example"
$EnvFile = Join-Path $Root ".env"
$VenvPython = Join-Path $Root ".venv\Scripts\python.exe"
$DevDatabaseUrl = "postgresql+psycopg://attention:attention@localhost:5432/attention?connect_timeout=5"

function Require-Command([string]$Name, [string]$InstallHint) {
    if (-not (Get-Command $Name -ErrorAction SilentlyContinue)) {
        throw "$Name is required. $InstallHint"
    }
}

Require-Command "docker" "Install Docker Desktop and ensure it is running."
Require-Command "python" "Install Python 3.11 or newer and add it to PATH."
Require-Command "npm" "Install Node.js 20 or newer, which includes npm."
Require-Command "node" "Install Node.js 20 or newer and add it to PATH."

if (-not (Test-Path $ComposeFile)) { throw "Missing docker-compose.yml at $ComposeFile" }
if (-not (Test-Path (Join-Path $Root "alembic.ini"))) { throw "Missing alembic.ini" }
if (-not (Test-Path (Join-Path $Root "pyproject.toml"))) { throw "Missing pyproject.toml" }

$pythonVersion = & python -c "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')"
$versionParts = $pythonVersion.Split('.') | ForEach-Object { [int]$_ }
if (($versionParts[0] -lt 3) -or (($versionParts[0] -eq 3) -and ($versionParts[1] -lt 11))) {
    throw "Python 3.11 or newer is required; found $pythonVersion"
}
$nodeVersion = (& node -p "process.versions.node").Trim().Split('.')[0]
if ([int]$nodeVersion -lt 20) { throw "Node.js 20 or newer is required; found $(& node --version)" }

& docker info *> $null
if ($LASTEXITCODE -ne 0) { throw "Docker Desktop is not running or this user cannot access the Docker daemon." }
& docker compose version *> $null
if ($LASTEXITCODE -ne 0) { throw "Docker Compose v2 is required (docker compose version failed)." }

if (-not (Test-Path $EnvFile)) {
    Copy-Item $EnvExample $EnvFile
    Write-Host "Created .env from .env.example; review local values before production-like use."
}

if (-not (Test-Path $VenvPython)) {
    & python -m venv (Join-Path $Root ".venv")
    if ($LASTEXITCODE -ne 0) { throw "Python virtual-environment creation failed." }
}
& $VenvPython -m pip install --upgrade pip
if ($LASTEXITCODE -ne 0) { throw "Python packaging bootstrap failed." }
& $VenvPython -m pip install -e ".[dev]"
if ($LASTEXITCODE -ne 0) { throw "Python dependency installation failed." }
& npm ci
if ($LASTEXITCODE -ne 0) { throw "Node dependency installation failed." }

& docker compose up -d db
if ($LASTEXITCODE -ne 0) { throw "PostgreSQL Compose service failed to start." }
$containerId = (& docker compose ps -q db).Trim()
if (-not $containerId) { throw "PostgreSQL container did not start." }

for ($attempt = 1; $attempt -le 60; $attempt++) {
    $health = (& docker inspect --format "{{.State.Health.Status}}" $containerId).Trim()
    if ($health -eq "healthy") { break }
    if ($health -eq "unhealthy") { throw "PostgreSQL Compose service became unhealthy." }
    Start-Sleep -Seconds 2
    if ($attempt -eq 60) { throw "Timed out waiting for PostgreSQL Compose healthcheck." }
}

$env:DATABASE_URL = $DevDatabaseUrl
& $VenvPython -m alembic upgrade head
if ($LASTEXITCODE -ne 0) { throw "Development database migration failed; no test database migration was attempted." }

$null = & $VenvPython scripts\ensure_test_database.py --database-url $DevDatabaseUrl --database-name $TestDatabaseName
if ($LASTEXITCODE -ne 0) { throw "Dedicated test database creation failed." }
$testDatabaseUrl = "postgresql+psycopg://attention:attention@localhost:5432/$TestDatabaseName?connect_timeout=5"
$env:DATABASE_URL = $testDatabaseUrl
$env:TEST_DATABASE_URL = $testDatabaseUrl
& $VenvPython -m alembic upgrade head
if ($LASTEXITCODE -ne 0) { throw "Test database migration failed." }

@("# Generated by scripts/setup.ps1; local-only and ignored by Git.", "DATABASE_URL=$DevDatabaseUrl", "TEST_DATABASE_URL=$testDatabaseUrl") |
    Set-Content -Path (Join-Path $Root ".env.test") -Encoding utf8

Write-Host "Setup complete. Development database: attention; isolated test database: $TestDatabaseName."
Write-Host "Start the application with: .\scripts\start.ps1"
Write-Host "Run PostgreSQL integration tests with: .\scripts\test-postgres.ps1"
